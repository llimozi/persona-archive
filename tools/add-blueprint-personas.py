def main():
    data = json.load(open(DATA, encoding="utf-8"))
    existing = {p["id"] for p in data["personas"]}
    added = 0
    for card in NEW:
        if card["id"] in existing:
            continue
        persona = {
            "id": card["id"],
            "name": card["name"],
            "category": card["category"],
            "tags": card["tags"],
            "dims": card["dims"],
            "desc": card["desc"],
            "cardType": "text",
            "placeholder": True,
            "imageUrl": f"/assets/personas/{card['id']}.png",
            "imageKind": "placeholder",
            "source": f"docs/spec/04-热梗与人物资料卡.md#{card['id']}",
            "evidence": "OBSERVED",
            "compliance": {
                "restricted": True,
                "restrictedReason": ["thirdPartyIP"],
                "matchPool": True,
                "resultCardEnabled": True,
            },
            "usageNote": card["usageNote"],
            "rarity": card["rarity"],
            "rarityBasis": f"04 §2.2 可匹配池计入；本卡 rarity 由主控按内容特征判定（{card['rarity']}）",
        }
        data["personas"].append(persona)
        existing.add(card["id"])
        added += 1

    data["note"] = data.get("note", "") if isinstance(data.get("note"), str) else ""
    with open(DATA, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"新增 {added} 人，当前共 {len(data['personas'])} 人")


if __name__ == "__main__":
    main()
